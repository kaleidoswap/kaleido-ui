#!/usr/bin/env node
/**
 * Derive a brand color from each icon PNG in a directory and emit a generated
 * token map. Run whenever icons are added/changed in a consumer app:
 *
 *   node scripts/generate-icon-colors.mjs <path-to-icons-dir>
 *
 * Writes src/tokens/icon-colors.generated.ts (keyed by icon basename). The
 * dominant color = the highest-scoring quantized bucket of opaque pixels,
 * weighted by saturation so grays/whites/blacks don't win.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { PNG } from "pngjs";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: generate-icon-colors.mjs <icons-dir>");
  process.exit(1);
}

function dominantColor(buf) {
  const png = PNG.sync.read(buf);
  const buckets = new Map(); // key -> {score,r,g,b,n}
  for (let i = 0; i < png.data.length; i += 4) {
    const r = png.data[i], g = png.data[i + 1], b = png.data[i + 2], a = png.data[i + 3];
    if (a < 200) continue;
    const max = Math.max(r, g, b), min = Math.min(r, g, b);
    const sat = max === 0 ? 0 : (max - min) / max;
    const lum = (r + g + b) / 765;
    if (lum > 0.95 || lum < 0.06) continue; // near-white/near-black
    const key = ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4);
    const e = buckets.get(key) ?? { score: 0, r: 0, g: 0, b: 0, n: 0 };
    e.score += sat + 0.15;
    e.r += r; e.g += g; e.b += b; e.n += 1;
    buckets.set(key, e);
  }
  let best = null;
  for (const e of buckets.values()) if (!best || e.score > best.score) best = e;
  if (!best) return null;
  const hex = (v) => Math.round(v / best.n).toString(16).padStart(2, "0");
  return `#${hex(best.r)}${hex(best.g)}${hex(best.b)}`.toUpperCase();
}

const out = {};
for (const f of readdirSync(resolve(dir)).sort()) {
  if (!f.endsWith(".png")) continue;
  try {
    const color = dominantColor(readFileSync(join(resolve(dir), f)));
    if (color) out[basename(f, ".png")] = color;
  } catch (err) {
    console.warn(`skip ${f}: ${err.message}`);
  }
}

const body = Object.entries(out)
  .map(([k, v]) => `  '${k}': '${v}',`)
  .join("\n");
writeFileSync(
  "src/tokens/icon-colors.generated.ts",
  `// AUTO-GENERATED by scripts/generate-icon-colors.mjs — do not edit by hand.\n// Source: dominant color extracted from each icon PNG.\nexport const iconColors: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`icon-colors: ${Object.keys(out).length} entries written`);
