test('the README’s token table matches the tokens', () => {
  const problems: Problems = []
  const section = /^## Design Tokens$([\s\S]*?)^## /m.exec(read('README.md'))?.[1] ?? ''
  assert.ok(section, 'README.md has no "## Design Tokens" section')
  for (const [, name, values] of section.matchAll(/^\| `(\w+)` \| (.*) \|$/gm)) {
    const token = (tokens as Record<string, unknown>)[name] as Record<string, unknown> | undefined
    if (token === undefined) {
      problems.push(`\`${name}\` is not exported by kaleido-ui/tokens`)
      continue
    }
    const plain = values.replace(/`/g, '')
    // "mini (10px)", "fast (150ms)", "primary (#15E99A, dark theme; …)": key (value).
    // "Satoshi (display)": value (key).
    for (const [, before, inside] of plain.matchAll(/([\w#. -]+?)\s*\(([^)]+)\)/g)) {
      const key = before.trim().split(/\s+/).pop()!
      if (key in token) {
        const actual = String(Array.isArray(token[key]) ? (token[key] as unknown[])[0] : token[key])
        const quoted = inside.split(/[,;]/)[0].trim()
        if (actual !== quoted && !actual.startsWith(`${quoted} `)) problems.push(`\`${name}.${key}\` is ${actual}, not ${quoted}`)
      } else if (inside in token) {
        const quoted = before.trim().split(/\s+(?:through|plus)\s+/).pop()!.replace(/^.*,\s*/, '')
        if (!String(token[inside]).includes(quoted)) problems.push(`\`${name}.${inside}\` is ${String(token[inside])}, not ${quoted}`)
      }
    }
    // "glow*, glowPrimary*" and "plus card, panel, nav, pill": key names.
    const listed = [
      ...[...plain.matchAll(/\b(\w+)\*/g)].map(([, prefix]) => `${prefix}*`),
      ...(/plus ([\w, ]+)$/.exec(plain)?.[1].split(',').map((key) => key.trim()) ?? []),
    ]
    for (const key of listed) {
      const ok = key.endsWith('*') ? Object.keys(token).some((k) => k.startsWith(key.slice(0, -1))) : key in token
      if (!ok) problems.push(`\`${name}\` has no key \`${key}\``)
    }
  }
  assert.deepEqual(problems, [])
})

