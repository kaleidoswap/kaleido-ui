// README.md and DESIGN.md are written by hand, and both drifted from the code:
// the README listed three of the forty-odd exported functions, DESIGN.md gave
// the page background and the label token values the tokens no longer had.
// This checks every statement in them that names something in the code against
// the code itself:
//
//   - every component, hook and function named exists and is exported, and
//     every prop named on a component (`IconButton icon label`,
//     `PageHeader variant="page"`, JSX in examples) is one of its props, with
//     that value where a value is given;
//   - every utility class named is generated by Tailwind v4 with kaleido-ui's
//     theme, and every other identifier (a variant, a CSS variable, a token
//     key) occurs in the source;
//   - every colour value occurs in the source, every file path exists, every
//     `kaleido-ui/*` import is a package entry point, every npm script and
//     package named exists;
//   - the numbers: type steps, spacing steps, radii, weights, the README's
//     token table and Button's variant and size counts;
//   - the code examples: their imports, their JSX and the token values their
//     comments print;
//   - every function and hook the web entry exports is listed in the README.
//
// What a sentence *means* (why a button is 44 px tall) is left to review.
// `src/tokens/` and the components are the source of truth: when this fails,
// the document is the bug.

const ROOT = join(import.meta.dirname, '..')
const read = (path: string) => readFileSync(join(ROOT, path), 'utf8').replace(/\r\n/g, '\n')
const pkg = JSON.parse(read('package.json')) as {
  exports: Record<string, unknown>
  scripts: Record<string, string>
  dependencies?: Record<string, string>
  devDependencies?: Record<string, string>
  peerDependencies?: Record<string, string>
}

const files = (dir: string, match: RegExp): string[] =>
  !existsSync(dir)
    ? []
    : readdirSync(dir).flatMap((name) => {
        const path = join(dir, name)
        if (statSync(path).isDirectory()) return files(path, match)
        return match.test(name) ? [path] : []
      })

// ── The documents ──────────────────────────────────────────────────────────

interface Doc {
  name: string
  text: string
  /** DESIGN.md's YAML front matter (empty for the README). */
  front: string
  /** The text with front matter and fenced blocks blanked, line numbers kept. */
  prose: string
}

const blank = (text: string) => text.replace(/[^\n]/g, '')

const loadDoc = (name: string): Doc => {
  const text = read(name)
  const front = /^---\n[\s\S]*?\n---\n/.exec(text)?.[0] ?? ''
  const prose = (blank(front) + text.slice(front.length)).replace(/^```[\s\S]*?^```/gm, blank)
  return { name, text, front, prose }
}

const DOCS = ['README.md', 'DESIGN.md'].map(loadDoc)
const DESIGN = DOCS[1]

const lineAt = (text: string, index: number) => text.slice(0, index).split('\n').length

/**
 * A value quoted as something not to do ("do not use raw `#0a0a0a`", "DON'T
 * …") or as history (the "Keeping this file honest" section, which says what
 * the file used to get wrong) is not a claim about the code.
 */
const outsideTheRules = (doc: Doc, index: number): boolean => {
  const line = doc.prose.split('\n')[lineAt(doc.prose, index) - 1]
  if (/\b(not|never|DON'T)\b/.test(line)) return true
  const history = doc.prose.indexOf('## Keeping this file honest')
  return history !== -1 && index > history
}

interface Span {
  where: string
  code: string
}

/** Inline code spans in a document's prose. `\|` inside a table cell is a `|`. */
const spansOf = (doc: Doc): Span[] =>
  [...doc.prose.matchAll(/`([^`\n]+)`/g)].map((match) => ({
    where: `${doc.name}:${lineAt(doc.prose, match.index!)}`,
    code: match[1].replace(/\\\|/g, '|'),
  }))

interface Block {
  where: string
  lang: string
  code: string
}

const blocksOf = (doc: Doc): Block[] =>
  [...doc.text.slice(doc.front.length).matchAll(/^```(\w*)\n([\s\S]*?)^```/gm)].map((match) => ({
    where: `${doc.name}:${lineAt(doc.text, doc.front.length + match.index!)}`,
    lang: match[1],
    code: match[2],
  }))

const SPANS = DOCS.flatMap(spansOf)
const BLOCKS = DOCS.flatMap(blocksOf)

/** Every key DESIGN.md's front matter defines (`brand.primary`, `card`, `tile-size`, …). */
const YAML_KEYS = new Set([...DESIGN.front.matchAll(/^\s*([A-Za-z0-9_.-]+):/gm)].map(([, key]) => key))

/** Names DESIGN.md defines for itself as a list head: "- `glass.nav` — floating chrome". */
const DEFINED = new Set([...DESIGN.prose.matchAll(/^- `([\w.-]+)` —/gm)].map(([, name]) => name))

