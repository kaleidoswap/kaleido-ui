const STEPS = Object.keys(tokens.typeScale).join('|')
const px = (value: string) => Number.parseFloat(value)
const SPACING_PX = px(tokens.spacingUnit) * 16

test('type steps the documents quote are the type scale', () => {
  const problems: Problems = []
  const size = (step: string) => px((tokens.typeScale as Record<string, readonly string[]>)[step][0])
  for (const doc of DOCS) {
    // "`caption` (13 px)", "`headline` (28 px)", "| `display` 38 |"
    for (const match of doc.prose.matchAll(new RegExp(`\`(${STEPS})\`\\s*(?:\\((\\d+) ?px\\)|(\\d+)\\b(?! ?\\/))`, 'g'))) {
      const [, step, inParens, bare] = match
      const quoted = Number(inParens ?? bare)
      if (quoted !== size(step)) {
        problems.push(`${doc.name}:${lineAt(doc.prose, match.index!)}: \`${step}\` is ${size(step)} px, not ${quoted}`)
      }
    }
  }
  // "**`display` — Satoshi 700 / 38 / 44": size and line height.
  for (const match of DESIGN.prose.matchAll(new RegExp(`\\*\\*\`(${STEPS})\`[^—\\n]*— Satoshi (\\d+) \\/ (\\d+) \\/ (\\d+)`, 'g'))) {
    const [, step, , fontSize, line] = match
    const [s, l] = (tokens.typeScale as Record<string, readonly string[]>)[step].map(px)
    if (Number(fontSize) !== s || Number(line) !== l) {
      problems.push(`DESIGN.md:${lineAt(DESIGN.prose, match.index!)}: \`${step}\` is ${s} / ${l}, not ${fontSize} / ${line}`)
    }
  }
  // Front matter rows (`label` is the `mini` step), and the prose about each against its row.
  const rows = new Map(
    [...DESIGN.front.matchAll(/^\s*(\w+):\s*\{([^}]*)\}/gm)].map(([, name, body]) => [
      name,
      Object.fromEntries([...body.matchAll(/(\w+):\s*"?([^,"]+)"?/g)].map(([, key, value]) => [key, value.trim()])),
    ]),
  )
  for (const [name, row] of rows) {
    const step = name === 'label' ? 'mini' : name
    if (step in tokens.typeScale) {
      const [s, l] = (tokens.typeScale as Record<string, readonly string[]>)[step].map(px)
      if (Number(row.size) !== s || Number(row.line) !== l) {
        problems.push(`DESIGN.md front matter: typography.${name} is ${row.size} / ${row.line}, the type scale says ${s} / ${l}`)
      }
    }
    const prose = new RegExp(`\`${name}\`[^—\\n]*— (?:Satoshi|Geist Mono) (\\d+) \\/ (\\d+)`).exec(DESIGN.prose)
    if (prose && (prose[1] !== row.weight || prose[2] !== row.size)) {
      problems.push(`DESIGN.md:${lineAt(DESIGN.prose, prose.index)}: \`${name}\` is ${prose[1]} / ${prose[2]} here, ${row.weight} / ${row.size} in the front matter`)
    }
  }
  assert.deepEqual(problems, [])
})

