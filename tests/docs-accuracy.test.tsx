test('the code examples import, render and print what the package has', () => {
  const problems: Problems = []
  const distBuilt = existsSync(join(ROOT, 'dist'))
  for (const { where, lang, code } of BLOCKS) {
    // Imports and requires of the package.
    for (const [, names, specifier] of code.matchAll(/import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+['"]([^'"]+)['"]/g)) {
      if (!specifier.startsWith('kaleido-ui')) continue
      checkImportPath(where, specifier, problems)
      const entry = exportsOf.get(specifier)
      for (const name of names.split(',').map((n) => n.trim().replace(/^type\s+/, '')).filter(Boolean)) {
        if (entry && !entry.has(name)) problems.push(`${where}: \`${specifier}\` does not export \`${name}\``)
      }
    }
    for (const [, specifier] of code.matchAll(/(?:require\(|@import\s+)['"](kaleido-ui[^'"]*)['"]/g)) checkImportPath(where, specifier, problems)

    // Paths into the installed package: `../node_modules/kaleido-ui/dist/web/**/*.js`.
    for (const [, path] of code.matchAll(/node_modules\/kaleido-ui\/([^'"\s]+)/g)) {
      const dir = path.split('/').filter((part) => !part.includes('*')).join('/')
      if (!distBuilt && dir.startsWith('dist')) continue
      if (!existsSync(join(ROOT, dir)) || files(join(ROOT, dir), /\.js$/).length === 0) {
        problems.push(`${where}: \`${path}\` matches no file the package ships`)
      }
    }

    // JSX.
    if (lang === 'tsx') {
      for (const match of code.matchAll(/<([A-Z][\w.]*)((?:\s+[a-z][\w-]*(?:=(?:"[^"]*"|'[^']*'|\{[^{}]*\}))?)*)\s*\/?>/g)) {
        checkElement(where, match[1], match[2], problems)
      }
    }

    // `colors.primary // '#15E99A'`: the value the comment prints.
    for (const [, path, printed] of code.matchAll(/^\s*(?:console\.log\()?([a-z]\w*(?:\.\w+)+)\)?\s*\/\/\s*(.+?)\s*$/gm)) {
      const actual = tokenAt(path)
      let expected: unknown
      try {
        expected = JSON.parse(printed.replace(/'/g, '"'))
      } catch {
        continue
      }
      if (JSON.stringify(actual) !== JSON.stringify(expected)) {
        problems.push(`${where}: \`${path}\` is ${JSON.stringify(actual)}, the example prints ${printed}`)
      }
    }
    // `t.colors.primary` in a `node -e` against the built tokens.
    for (const [, path] of code.matchAll(/\bt\.([a-z]\w*(?:\.\w+)*)/g)) {
      if (tokenAt(path) === undefined) problems.push(`${where}: tokens have no \`${path}\``)
    }

    // npm scripts and packages.
    if (lang === 'bash') {
      for (const [, script] of code.matchAll(/npm run (?:-s )?([\w:-]+)/g)) {
        if (!(script in pkg.scripts)) problems.push(`${where}: there is no npm script \`${script}\``)
      }
      for (const [, args] of code.matchAll(/npm install ([^\n#]*)/g)) {
        for (const name of args.split(/\s+/).filter((arg) => arg && !arg.startsWith('-'))) {
          if (!KNOWN_PACKAGES.has(name)) problems.push(`${where}: \`${name}\` is not a dependency of kaleido-ui`)
        }
      }
    }
  }
  assert.deepEqual(problems, [])
})

