const config = ts.getParsedCommandLineOfConfigFile(join(ROOT, 'tsconfig.json'), {}, {
  ...ts.sys,
  onUnRecoverableConfigFileDiagnostic: () => undefined,
})!
const program = ts.createProgram(Object.values(ENTRIES).map((path) => join(ROOT, path)), config.options)
const checker = program.getTypeChecker()

const exportsOf = new Map<string, Map<string, ts.Symbol>>()
for (const [entry, path] of Object.entries(ENTRIES)) {
  const source = program.getSourceFile(join(ROOT, path))
  const module = source && checker.getSymbolAtLocation(source)
  assert.ok(module, `${path} did not load`)
  exportsOf.set(entry, new Map(checker.getExportsOfModule(module).map((symbol) => [symbol.name, symbol])))
}

/** The symbols exported under a name, from any entry point. */
const exported = (name: string): ts.Symbol[] =>
  [...exportsOf.values()].flatMap((names) => (names.has(name) ? [names.get(name)!] : []))

const resolve = (symbol: ts.Symbol) =>
  symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol

const typeOf = (symbol: ts.Symbol) => checker.getTypeOfSymbol(resolve(symbol))

/** A component's props types: the first parameter of a function component, `props` of a class one. */
const propsTypes = (symbol: ts.Symbol): ts.Type[] => {
  if (!(resolve(symbol).flags & ts.SymbolFlags.Value)) return []
  const type = typeOf(symbol)
  return [
    ...type.getCallSignatures().flatMap((signature) => {
      const props = signature.getParameters()[0]
      return props ? [checker.getTypeOfSymbol(props)] : []
    }),
    ...type.getConstructSignatures().flatMap((signature) => {
      const props = signature.getReturnType().getProperty('props')
      return props ? [checker.getTypeOfSymbol(props)] : []
    }),
  ]
}

const parts = (type: ts.Type): ts.Type[] => (type.isUnion() ? type.types : [type])

const propOf = (types: ts.Type[], name: string): ts.Symbol | undefined => {
  for (const type of types) {
    for (const part of parts(type)) {
      const prop = checker.getPropertyOfType(checker.getApparentType(part), name)
      if (prop) return prop
    }
  }
}

/** Whether a prop accepts a string value: any string, or that literal. */
const acceptsString = (prop: ts.Symbol, value: string): boolean =>
  parts(checker.getNonNullableType(checker.getTypeOfSymbol(prop))).some(
    (part) => !!(part.flags & ts.TypeFlags.String) || (part.isStringLiteral() && part.value === value),
  )

/** The string literals a prop accepts, for messages and counts. */
const literalsOf = (prop: ts.Symbol): string[] =>
  parts(checker.getNonNullableType(checker.getTypeOfSymbol(prop))).flatMap((part) =>
    part.isStringLiteral() ? [part.value] : [],
  )

/** Every source file and config the documents may name things from. */
const CORPUS = [
  ...files(join(ROOT, 'src'), /\.(tsx?|css|json)$/).map((path) => readFileSync(path, 'utf8')),
  ...files(join(ROOT, 'scripts'), /\.(tsx?|mjs)$/).map((path) => readFileSync(path, 'utf8')),
  read('package.json'),
  read('tsup.config.ts'),
  ...readdirSync(join(ROOT, 'brand')),
].join('\n')

const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Whether a name occurs in the code as a whole word; `*` matches any run of name characters. */
const inCorpus = (name: string): boolean => {
  const pattern = name.split('*').map(escape).join('[\\w-]*')
  return new RegExp(`(?<![\\w-])${pattern}(?![\\w-])`).test(CORPUS)
}

const CORPUS_LOWER_NO_SPACE = CORPUS.toLowerCase().replace(/\s+/g, '')

/** Tokens path such as `colors.network.bitcoin`, or undefined. */
const tokenAt = (path: string): unknown =>
  path.split('.').reduce<unknown>((value, key) => (value as Record<string, unknown> | undefined)?.[key], tokens)

