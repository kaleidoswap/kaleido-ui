test('radii the documents quote are the radius tokens', () => {
  const problems: Problems = []
  const rounded = new Map(
    [...(/^rounded:\n((?:\s+.*\n)+?)(?=\S)/m.exec(DESIGN.front)?.[1] ?? '').matchAll(/^\s*([\w-]+):\s*(\d+)/gm)].map(([, key, value]) => [key, Number(value)]),
  )
  const radiusPx = (name: string) => px((tokens.radius as Record<string, string>)[name])
  const same = (a: number, b: number) => a === b || (a >= 999 && b >= 999)
  // "**`card: 16` (`rounded-2xl`)**"
  for (const match of DESIGN.prose.matchAll(/`(\w+): (\d+)` \(`rounded-([\w-]+)`\)/g)) {
    const [, name, value, step] = match
    if (!same(Number(value), radiusPx(step))) problems.push(`DESIGN.md:${lineAt(DESIGN.prose, match.index!)}: \`rounded-${step}\` is ${radiusPx(step)} px, not ${value}`)
    if (rounded.has(name) && !same(rounded.get(name)!, Number(value))) problems.push(`DESIGN.md:${lineAt(DESIGN.prose, match.index!)}: \`${name}\` is ${rounded.get(name)} in the front matter, ${value} here`)
  }
  // "radius `card` (16)", "inner radius: `nav` (20)"
  for (const match of DESIGN.prose.matchAll(/`(\w+)` \((\d+)\)/g)) {
    const [, name, value] = match
    if (rounded.has(name) && !same(rounded.get(name)!, Number(value))) {
      problems.push(`DESIGN.md:${lineAt(DESIGN.prose, match.index!)}: \`${name}\` is ${rounded.get(name)} in the front matter, ${value} here`)
    }
  }
  // The ladder itself: card, panel, nav and pill are radius tokens of their own.
  for (const name of ['card', 'panel', 'nav', 'pill']) {
    if (rounded.has(name) && !same(rounded.get(name)!, radiusPx(name))) {
      problems.push(`DESIGN.md front matter: rounded.${name} is ${rounded.get(name)}, the radius token is ${radiusPx(name)} px`)
    }
  }
  assert.deepEqual(problems, [])
})

